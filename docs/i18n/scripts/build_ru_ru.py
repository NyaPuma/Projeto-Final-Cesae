# ============================================================ verify + generate
def verify():
    missing = []
    for dom in sorted(os.listdir(EN_DIR)):
        if not dom.endswith('.php'):
            continue
        d = load_php_file(os.path.join(EN_DIR, dom))
        base = dom[:-4]
        def walk(dd, prefix=''):
            for k, v in dd.items():
                p = prefix + str(k)
                if isinstance(v, dict):
                    walk(v, p + '.')
                else:
                    key = base + '.' + p
                    if key not in RU:
                        missing.append(key)
        walk(d)
    if missing:
        print('FALTAM %d traduções:' % len(missing))
        for m in sorted(missing):
            print('  ', m)
        return False
    return True

def build():
    if not verify():
        sys.exit(1)
    os.makedirs(RU_DIR, exist_ok=True)
    for dom in sorted(os.listdir(EN_DIR)):
        if not dom.endswith('.php'):
            continue
        d = load_php_file(os.path.join(EN_DIR, dom))
        base = dom[:-4]
        out = []
        out.append('<?php')
        out.append('')
        out.append('return [')
        def emit(dd, prefix='', indent=0):
            pad = '    ' * (indent + 1)
            for k, v in dd.items():
                p = prefix + str(k)
                key_lit = "'" + k.replace("\\", "\\\\").replace("'", "\\'") + "'"
                if isinstance(v, dict):
                    out.append('%s%s => [' % (pad, key_lit))
                    emit(v, p + '.', indent + 1)
                    out.append('%s],' % pad)
                else:
                    val = RU[base + '.' + p]
                    val_lit = "'" + val.replace("\\", "\\\\").replace("'", "\\'") + "'"
                    out.append('%s%s => %s,' % (pad, key_lit, val_lit))
        emit(d)
        out.append('];')
        out.append('')
        path = os.path.join(RU_DIR, dom)
        with open(path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(out))
        print('gerado', dom)

if __name__ == '__main__':
    build()
